def read_pdf(path: str) -> list[dict]:
    """Opens and reads the pdf and returns information on the pages."""
    pdf = pymupdf.open(pdf_path)
    pages_and_texts = []
    for page_number, page in enumerate(pdf):
        text = page.get_text()
        text = format(text=text)
