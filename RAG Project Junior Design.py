def user(user_message, history):
    return "", history + [[user_message, None]]

def bot(history):
    generation_state.stop_generation = False
    user_message = history[-1][0]
    bot_message = generate_response(user_message)
    history[-1][1] = ""
    for character in bot_message:
        if generation_state.stop_generation:
            break
        history[-1][1] += character
        time.sleep(0.02)  # Reduced delay for faster response
        yield history

    if generation_state.stop_generation:
        history[-1][1] += " [Generation stopped]"
        yield history

def stop_generation():
    generation_state.stop_generation = True

